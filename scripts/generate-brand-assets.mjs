/** Pack PNG buffers into a PNG-encoded ICO (supported by all modern browsers). */
function buildIco(entries) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(entries.length, 4);

  const dirSize = 16 * entries.length;
  let offset = 6 + dirSize;
  const dirs = [];
  for (const { size, png } of entries) {
    const dir = Buffer.alloc(16);
    dir.writeUInt8(size >= 256 ? 0 : size, 0); // width
    dir.writeUInt8(size >= 256 ? 0 : size, 1); // height
    dir.writeUInt8(0, 2); // palette
    dir.writeUInt8(0, 3); // reserved
    dir.writeUInt16LE(1, 4); // color planes
    dir.writeUInt16LE(32, 6); // bits per pixel
    dir.writeUInt32LE(png.length, 8);
    dir.writeUInt32LE(offset, 12);
    offset += png.length;
    dirs.push(dir);
  }
  return Buffer.concat([header, ...dirs, ...entries.map((e) => e.png)]);
}

async function renderPng(page, html, { width, height, transparent }) {
  await page.setViewportSize({ width, height });
  await page.setContent(html, { waitUntil: "networkidle" });
  await page.evaluate(() => document.fonts.ready);
  return page.screenshot({ type: "png", omitBackground: transparent });
}

async function main() {
  const canonical = await readFile(CANONICAL_SVG, "utf8");
  const inner = extractInner(canonical);
  const squareSvg = squareIconSvg(inner);
  // Tight-bounds mark (geometry spans x 6.33–23.22, y 1.5–54.9) so flexbox
  // centering positions the visible mark — not the padded viewBox — dead center.
  const markSvg = `<svg viewBox="6.33 1.5 16.89 53.4" fill="none" xmlns="http://www.w3.org/2000/svg">${inner}</svg>`;

  await mkdir(path.join(ROOT, "public", "brand"), { recursive: true });

  const browser = await chromium.launch();
  const page = await browser.newPage();

  const out = async (rel, buf) => {
    await writeFile(path.join(ROOT, rel), buf);
    console.log(`✓ ${rel} (${buf.length} bytes)`);
  };

  // --- SVG favicon (square, transparent) ---
  await out("src/app/icon0.svg", Buffer.from(squareSvg, "utf8"));

  // --- Transparent square PNGs (favicon fallback + manifest/JSON-LD) ---
  // ~3% breathing room so edge antialiasing is never clipped, without the
  // excessive padding of the previous assets.
  const transparentSquare = async (size) =>
    renderPng(
      page,
      iconPageHtml(markSvg, { size, markHeight: Math.round(size * 0.94) }),
      {
        width: size,
        height: size,
        transparent: true,
      },
    );

  await out("src/app/icon1.png", await transparentSquare(512));
  await out("public/brand/clark-spine-icon-512.png", await transparentSquare(512));
  await out("public/brand/clark-spine-icon-192.png", await transparentSquare(192));

  // --- favicon.ico: PNG-encoded 16/32/48 entries, transparent ---
  const icoEntries = [];
  for (const size of [16, 32, 48]) {
    icoEntries.push({ size, png: await transparentSquare(size) });
  }
  await out("src/app/favicon.ico", buildIco(icoEntries));

  // --- Apple touch icon: 180×180 full-bleed background (iOS composites
  // transparent icons on black and rounds corners itself). Off-white keeps
  // the mark's navy-ending gradient readable — on navy it would vanish. ---
  const appleHtml = iconPageHtml(markSvg, {
    size: 180,
    markHeight: 144,
    background: `radial-gradient(circle at 50% 42%, #ffffff 0%, ${OFF_WHITE} 62%, #e8eff6 100%)`,
  });
  await out(
    "src/app/apple-icon.png",
    await renderPng(page, appleHtml, { width: 180, height: 180, transparent: false }),
  );

  // --- Open Graph / Twitter card: 1200×630 ---
  await out(
    "public/brand/clark-spine-og.png",
    await renderPng(page, ogPageHtml(markSvg), {
      width: 1200,
      height: 630,
      transparent: false,
    }),
  );

  await browser.close();
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
